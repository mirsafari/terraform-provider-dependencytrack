func (r *workloadIdentityBindingResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	// Load state.
	var state workloadIdentityBindingResourceModel
	diags := req.State.Get(ctx, &state)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Map TF to SDK.
	id, diag := TryParseUUID(state.UUID, LifecycleDelete, path.Root("uuid"))
	if diag != nil {
		resp.Diagnostics.Append(diag)
		return
	}
	serviceAccount := state.ServiceAccount.ValueString()

	// Execute.
	tflog.Debug(ctx, "Deleting Workload Identity Binding", map[string]any{
		"id":              state.ID.ValueString(),
		"service_account": serviceAccount,
	})
	err := r.client.ServiceAccount.DeleteWorkloadIdentityBinding(ctx, serviceAccount, id)
	if err != nil {
		err := err.Error()
		if err == "{\"type\":\"about:blank\",\"title\":\"Not Found\",\"detail\":\"The requested resource could not be found.\",\"status\":404} (status: 404)" {
			tflog.Warn(ctx, "Unable to delete missing Workload Identity Binding. Ignoring since is desired state.", map[string]any{
				"id":              state.ID.ValueString(),
				"service_account": serviceAccount,
			})
			return
		}
		resp.Diagnostics.AddError(
			"Unable to delete Workload Identity Binding",
			"Unexpected error when trying to delete Workload Identity Binding: "+state.ID.ValueString()+", from error: "+err,
		)
		return
	}
	tflog.Debug(ctx, "Deleted Workload Identity Binding", map[string]any{
		"id":              state.ID.ValueString(),
		"service_account": serviceAccount,
	})
}

func (r *workloadIdentityBindingResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	idParts := strings.Split(req.ID, "/")
	if len(idParts) != 2 || idParts[0] == "" || idParts[1] == "" {
		resp.Diagnostics.AddError(
			"Unexpected import id",
			"Expected id in format <ServiceAccountName>/<UUID>. Received "+req.ID,
		)
		return
	}
	serviceAccount := idParts[0]
	id, diag := TryParseUUID(types.StringValue(idParts[1]), LifecycleImport, path.Root("uuid"))
	if diag != nil {
		resp.Diagnostics.Append(diag)
		return
	}
	tflog.Debug(ctx, "Importing Workload Identity Binding", map[string]any{
		"id":              req.ID,
		"service_account": serviceAccount,
	})
	binding, err := r.findBinding(ctx, serviceAccount, id)
	if err != nil {
		resp.Diagnostics.AddError(
			"Within Import, unable to identify Workload Identity Binding.",
			"Unexpected error: "+err.Error(),
		)
		return
	}

	bindingState := newWorkloadIdentityBindingModel(serviceAccount, *binding, types.StringNull())

	diags := resp.State.Set(ctx, bindingState)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}
	tflog.Debug(ctx, "Imported Workload Identity Binding", map[string]any{
		"id":              bindingState.ID.ValueString(),
		"service_account": bindingState.ServiceAccount.ValueString(),
	})
}

func (r *workloadIdentityBindingResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	clientInfoData, ok := req.ProviderData.(clientInfo)

	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Configure Type",
			fmt.Sprintf("Expected provider.clientInfo, got %T. Please report this issue to the provider developers.", req.ProviderData),
		)
		return
	}
	r.client = clientInfoData.client
	r.semver = clientInfoData.semver
}

// Bindings can only be listed per Service Account, so the binding is located by UUID within that list.
func (r *workloadIdentityBindingResource) findBinding(ctx context.Context, serviceAccount string, id uuid.UUID) (*dtrack.WorkloadIdentityBinding, error) {
	return FindPagedV5(
		func(pageToken string, limit uint32) (dtrack.PageV5[dtrack.WorkloadIdentityBinding], error) {
			return r.client.ServiceAccount.ListWorkloadIdentityBindings(ctx, serviceAccount, pageToken, limit)
		},
		func(binding dtrack.WorkloadIdentityBinding) bool {
			return binding.UUID == id
		},
	)
}

// Maps the API response to the Terraform model. An absent condition is null, unless it was previously known as empty.
func newWorkloadIdentityBindingModel(
	serviceAccount string,
	binding dtrack.WorkloadIdentityBinding,
	condition types.String,
) workloadIdentityBindingResourceModel {
	model := workloadIdentityBindingResourceModel{
		ID:             types.StringValue(fmt.Sprintf("%s/%s", serviceAccount, binding.UUID.String())),
		UUID:           types.StringValue(binding.UUID.String()),
		ServiceAccount: types.StringValue(serviceAccount),
		ProviderName:   types.StringValue(binding.ProviderName),
		Subject:        types.StringValue(binding.Subject),
		Condition:      types.StringNull(), // Conditionally Set Below.
		CreatedAt:      types.Int64Value(binding.CreatedAt),
	}
	if !condition.IsNull() || binding.Condition != "" {
		model.Condition = types.StringValue(binding.Condition)
	}
	return model
}
