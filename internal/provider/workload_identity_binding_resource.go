func (r *workloadIdentityBindingResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan workloadIdentityBindingResourceModel
	diags := req.Plan.Get(ctx, &plan)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	serviceAccount := plan.ServiceAccount.ValueString()
	bindingReq := dtrack.CreateWorkloadIdentityBindingRequest{
		ProviderName: plan.ProviderName.ValueString(),
		Subject:      plan.Subject.ValueString(),
		Condition:    plan.Condition.ValueString(),
	}

	tflog.Debug(ctx, "Creating Workload Identity Binding", map[string]any{
		"service_account": serviceAccount,
		"provider_name":   bindingReq.ProviderName,
		"subject":         bindingReq.Subject,
	})

	bindingRes, err := r.client.ServiceAccount.CreateWorkloadIdentityBinding(ctx, serviceAccount, bindingReq)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error creating Workload Identity Binding",
			"Error in: "+serviceAccount+", in original error: "+err.Error(),
		)
		return
	}

	binding, err := r.findBinding(ctx, serviceAccount, bindingRes.UUID)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error while creating Workload Identity Binding",
			"Error reading after creation in: "+serviceAccount+"/"+bindingRes.UUID.String()+", in original error: "+err.Error(),
		)
		return
	}
	newState := newWorkloadIdentityBindingModel(serviceAccount, *binding, plan.Condition)

	diags = resp.State.Set(ctx, newState)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}
	tflog.Debug(ctx, "Created Workload Identity Binding", map[string]any{
		"id":              newState.ID.ValueString(),
		"service_account": newState.ServiceAccount.ValueString(),
	})
}

func (r *workloadIdentityBindingResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	// Fetch state.
	var state workloadIdentityBindingResourceModel
	diags := req.State.Get(ctx, &state)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Refresh.
	id, diag := TryParseUUID(state.UUID, LifecycleRead, path.Root("uuid"))
	if diag != nil {
		resp.Diagnostics.Append(diag)
		return
	}
	serviceAccount := state.ServiceAccount.ValueString()
	tflog.Debug(ctx, "Reading Workload Identity Binding", map[string]any{
		"id":              state.ID.ValueString(),
		"service_account": serviceAccount,
	})

	binding, err := r.findBinding(ctx, serviceAccount, id)
	if err != nil {
		err := err.Error()
		missing := err == "did not find item" ||
			err == "{\"type\":\"about:blank\",\"title\":\"Not Found\",\"detail\":\"The requested resource could not be found.\",\"status\":404} (status: 404)"
		if missing {
			tflog.Warn(ctx, "Unable to read missing Workload Identity Binding. Will be removed from state.", map[string]any{
				"id":              state.ID.ValueString(),
				"service_account": serviceAccount,
			})
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError(
			"Error when reading Workload Identity Binding.",
			"Error in binding with id: "+state.ID.ValueString()+", in original error: "+err,
		)
		return
	}

	newState := newWorkloadIdentityBindingModel(serviceAccount, *binding, state.Condition)

	// Update state.
	diags = resp.State.Set(ctx, newState)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}
	tflog.Debug(ctx, "Read Workload Identity Binding", map[string]any{
		"id":              newState.ID.ValueString(),
		"service_account": newState.ServiceAccount.ValueString(),
	})
}

